/* Service worker di Quadretti.
   Tiene in cache i file dell'app cosi' il gioco funziona anche senza rete.
   ATTENZIONE: dopo ogni modifica ai file, alza il numero di CACHE
   (v1 -> v2 e cosi' via), altrimenti i telefoni continuano a usare
   la versione vecchia salvata in cache. */

var CACHE = 'quadretti-v6';

var FILES = [
  './',
  './index.html',
  './app.css',
  './app.js',
  './levels.js',
  './generator.js',
  './sound.js',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable.png'
];

self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(CACHE)
      .then(function (c) { return c.addAll(FILES); })
      .then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys()
      .then(function (keys) {
        return Promise.all(keys.map(function (k) {
          return k === CACHE ? null : caches.delete(k);
        }));
      })
      .then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('fetch', function (e) {
  if (e.request.method !== 'GET') return;

  e.respondWith(
    caches.match(e.request).then(function (hit) {
      if (hit) return hit;
      return fetch(e.request).then(function (res) {
        if (res && res.status === 200 && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(e.request, copy); });
        }
        return res;
      }).catch(function () {
        return caches.match('./index.html');
      });
    })
  );
});
